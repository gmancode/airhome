//! UI translations: English, Russian, Spanish, German, French, Portuguese, Chinese, Japanese.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En = 0,
    Ru = 1,
    Es = 2,
    De = 3,
    Fr = 4,
    Pt = 5,
    Zh = 6,
    Ja = 7,
}

impl Lang {
    pub const ALL: [Lang; 8] = [Lang::En, Lang::Ru, Lang::Es, Lang::De, Lang::Fr, Lang::Pt, Lang::Zh, Lang::Ja];

    pub fn code(self) -> &'static str {
        ["en", "ru", "es", "de", "fr", "pt", "zh", "ja"][self as usize]
    }

    pub fn from_code(code: &str) -> Option<Lang> {
        Lang::ALL.into_iter().find(|l| l.code() == code)
    }

    /// Each language is shown in its own language.
    pub fn native_name(self) -> &'static str {
        ["English", "Русский", "Español", "Deutsch", "Français", "Português", "中文", "日本語"][self as usize]
    }

    /// Guess from the Windows UI language.
    pub fn detect() -> Lang {
        #[cfg(windows)]
        {
            #[link(name = "kernel32")]
            extern "system" {
                fn GetUserDefaultUILanguage() -> u16;
            }
            let id = unsafe { GetUserDefaultUILanguage() } & 0x3ff;
            return match id {
                0x19 => Lang::Ru,
                0x0A => Lang::Es,
                0x07 => Lang::De,
                0x0C => Lang::Fr,
                0x16 => Lang::Pt,
                0x04 => Lang::Zh,
                0x11 => Lang::Ja,
                _ => Lang::En,
            };
        }
        #[allow(unreachable_code)]
        Lang::En
    }
}

